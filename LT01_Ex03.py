# Receba a base e a altura de um triângulo. Calcule e mostre a sua área.

# inicio.
Base = float(input('Digite a base do triângulo e tecle Enter: '))
Altura = float(input('Digite a altura do triângulo e tecle Enter: '))
Area = (Base * Altura)/2
print('A área do triângulo é:', Area)
